// usageView is the overview's token panel: the four kinds of token,
// which do not overlap, overall and by harness
// (TKT-01M61NTE24T6CZN1P92AV7164F).
type usageView struct {
	Shown bool
	Total tokenCell
	Parts []usagePart
	Rows  []usageRow
	// Partial says some ready sessions the viewer reads are not
	// indexed yet, so the totals leave them out.
	Partial          bool
	Indexed, Ready   int
	HasCost          bool
	Cost, Calls      string
	ToolCalls, Fails string
}

type usagePart struct {
	Label, Note string
	Cell        tokenCell
}

// tokenCell is a count shown short, "12.4M", with the exact count for
// its title. Missing is a count no counted event reported.
type tokenCell struct {
	Short, Exact string
	Missing      bool
}

type usageRow struct {
	Harness                                     string
	Sessions, Calls                             string
	Input, Output, CacheRead, CacheWrite, Total tokenCell
	Cost                                        string
}

func cellOf(p *int64) tokenCell {
	if p == nil {
		return tokenCell{Short: "—", Exact: "not reported", Missing: true}
	}
	return tokenCell{Short: shortCount(*p), Exact: humanCount(*p)}
}

// shortCount is n to three significant figures with a suffix: 987,
// 12.4K, 3.21M, 1.05B.
func shortCount(n int64) string {
	v := math.Abs(float64(n))
	sign := ""
	if n < 0 {
		sign = "−"
	}
	for _, u := range []struct {
		div    float64
		suffix string
	}{{1e12, "T"}, {1e9, "B"}, {1e6, "M"}, {1e3, "K"}} {
		if v >= u.div {
			x := v / u.div
			switch {
			case x >= 100:
				return fmt.Sprintf("%s%.0f%s", sign, x, u.suffix)
			case x >= 10:
				return fmt.Sprintf("%s%.1f%s", sign, x, u.suffix)
			}
			return fmt.Sprintf("%s%.2f%s", sign, x, u.suffix)
		}
	}
	return sign + fmt.Sprint(int64(v))
}

func costText(p *float64) string {
	if p == nil {
		return "—"
	}
	return fmt.Sprintf("$%.2f", *p)
}

// tokenTotal sums the kinds that were reported, or nil when none was.
func tokenTotal(t recall.Tokens) *int64 {
	var sum *int64
	for _, p := range []*int64{t.Input, t.Output, t.CacheRead, t.CacheWrite} {
		if p != nil {
			if sum == nil {
				sum = new(int64)
			}
			*sum += *p
		}
	}
	return sum
}

func buildUsageView(t recall.Totals) usageView {
	v := usageView{Shown: true, Total: cellOf(tokenTotal(t.All.Tokens)), Calls: humanCount(t.All.ModelCalls), ToolCalls: humanCount(t.All.ToolCalls), Fails: humanCount(t.All.ToolsFailed)}
	v.Parts = []usagePart{
		{"Input", "Not read from or written to the cache", cellOf(t.All.Tokens.Input)},
		{"Output", "Generated by the model", cellOf(t.All.Tokens.Output)},
		{"Cache read", "Input served from the prompt cache", cellOf(t.All.Tokens.CacheRead)},
		{"Cache write", "Input written to the prompt cache", cellOf(t.All.Tokens.CacheWrite)},
	}
	if t.All.Tokens.CostUSD != nil {
		v.HasCost, v.Cost = true, costText(t.All.Tokens.CostUSD)
	}
	v.Indexed, v.Ready = t.Coverage.Indexed, t.Coverage.Ready
	v.Partial = t.Coverage.Indexed < t.Coverage.Ready
	for _, h := range t.Harnesses {
		v.Rows = append(v.Rows, usageRow{
			Harness: h.Harness, Sessions: humanCount(h.Sessions), Calls: humanCount(h.ModelCalls),
			Input: cellOf(h.Tokens.Input), Output: cellOf(h.Tokens.Output), CacheRead: cellOf(h.Tokens.CacheRead), CacheWrite: cellOf(h.Tokens.CacheWrite),
			Total: cellOf(tokenTotal(h.Tokens)), Cost: costText(h.Tokens.CostUSD),
		})
	}
	return v
}

// usagePageView is the Usage page: tokens over time for a range and a
// harness, one chart per kind of token (TKT-01M61NTKY742C45NTZ8KN2CQJ7).
// The kinds differ by orders of magnitude, since cache reads dwarf the
// rest, so they are charted apart on their own scales rather than
// stacked, where input and output would not show.
type usagePageView struct {
	// Enabled is false on a lake with no search index.
	Enabled   bool
	Ranges    []activityRange
	Range     string
	Harness   string
	Harnesses []string
	Since     string
	Calls     string
	Parts     []usagePart
	Charts    []chartView
	Rows      []usageBucketRow
	Partial   bool
	Indexed   int
	Ready     int
}

type usageBucketRow struct {
	Start, Calls                         string
	Input, Output, CacheRead, CacheWrite tokenCell
}

// validStatsHarness accepts a harness name as the stats store it: short
// lowercase letters, digits and dashes. A name no session has selects
// nothing.
func validStatsHarness(h string) bool {
	if len(h) > 64 {
		return false
	}
	for _, c := range h {
		if !(c >= 'a' && c <= 'z' || c >= '0' && c <= '9' || c == '-') {
			return false
		}
	}
	return true
}

// usagePage renders /usage. Parameters are refused like Activity's: an
// unknown or repeated one is an error, an empty one takes the default.
func (s *Server) usagePage(w http.ResponseWriter, r *http.Request) {
	q := r.URL.Query()
	for k, v := range q {
		if len(v) != 1 || k != "range" && k != "harness" {
			pageError(w, r, catalog.ErrPage)
			return
		}
	}
	key := cmp.Or(q.Get("range"), "7d")
	i := slices.IndexFunc(activityRanges, func(a activityRange) bool { return a.Key == key })
	harness := q.Get("harness")
	if i < 0 || !validStatsHarness(harness) {
		pageError(w, r, catalog.ErrPage)
		return
	}
	preset := activityRanges[i]
	v := usagePageView{Ranges: activityRanges, Range: key, Harness: harness}
	if s.index == nil {
		render(w, r, pageData{Title: "Usage", View: "usage", UsagePage: v})
		return
	}
	v.Enabled = true
	now := s.now()
	resolved, err := catalog.ActivityRequest{Bucket: preset.Bucket}.Resolve(now)
	if err != nil {
		pageError(w, r, err)
		return
	}
	from, width := resolved.Until.Add(-preset.Span), time.Hour
	if preset.Bucket == catalog.BucketDay {
		width = 24 * time.Hour
	}
	ctx, cancel := readContext(r)
	defer cancel()
	scope := scopeOf(r)
	totals, err := s.index.Totals(ctx, scope)
	if err != nil {
		pageError(w, r, err)
		return
	}
	series, err := s.index.Series(ctx, scope, harness, from, resolved.Until, width)
	if err != nil {
		pageError(w, r, err)
		return
	}
	for _, h := range totals.Harnesses {
		v.Harnesses = append(v.Harnesses, h.Harness)
	}
	slices.Sort(v.Harnesses)
	v.Indexed, v.Ready = totals.Coverage.Indexed, totals.Coverage.Ready
	v.Partial = v.Indexed < v.Ready
	buildUsageSeries(&v, series, preset.Bucket == catalog.BucketHour)
	render(w, r, pageData{Title: "Usage", View: "usage", Poll: true, AsOf: now.UTC().Format(time.RFC3339Nano), UsagePage: v})
}

// buildUsageSeries fills the charts, the range totals and the table. A
// bucket with no model calls holds zero of every kind. A bucket whose
// calls did not report a kind is not measured for it, which is not the
// same as zero.
func buildUsageSeries(v *usagePageView, series []recall.SeriesBucket, hourly bool) {
	starts := make([]time.Time, len(series))
	kinds := []struct {
		id, title, label, note string
		get                    func(recall.Tokens) *int64
	}{
		{"input", "Input tokens", "Input", "Not read from or written to the cache", func(t recall.Tokens) *int64 { return t.Input }},
		{"output", "Output tokens", "Output", "Generated by the model", func(t recall.Tokens) *int64 { return t.Output }},
		{"cache-read", "Cache read tokens", "Cache read", "Input served from the prompt cache", func(t recall.Tokens) *int64 { return t.CacheRead }},
		{"cache-write", "Cache write tokens", "Cache write", "Input written to the prompt cache", func(t recall.Tokens) *int64 { return t.CacheWrite }},
	}
	values := make([][]*int64, len(kinds))
	var total recall.Tokens
	var calls int64
	for i, b := range series {
		starts[i] = b.Start
		calls += b.ModelCalls
		total.Add(b.Tokens)
		for k, kind := range kinds {
			p := kind.get(b.Tokens)
			if p == nil && b.ModelCalls == 0 {
				p = new(int64)
			}
			values[k] = append(values[k], p)
		}
		v.Rows = append(v.Rows, usageBucketRow{Start: bucketLabel(b.Start, hourly), Calls: humanCount(b.ModelCalls),
			Input: cellOf(b.Tokens.Input), Output: cellOf(b.Tokens.Output), CacheRead: cellOf(b.Tokens.CacheRead), CacheWrite: cellOf(b.Tokens.CacheWrite)})
	}
	v.Calls = humanCount(calls)
	for k, kind := range kinds {
		v.Parts = append(v.Parts, usagePart{kind.label, kind.note, cellOf(kind.get(total))})
		v.Charts = append(v.Charts, buildChart(kind.id, kind.title, starts, values[k], hourly, shortCount, niceCeil))
	}
}
